# Позиция заглавной (ударной) гласной в слове; None — если заглавная не одна или не гласная
def stress_index(word):
    caps = [i for i, ch in enumerate(word) if ch.isupper()]
    if len(caps) != 1 or word[caps[0]].lower() not in VOWELS:
        return None
    return caps[0]



# Словарь ударений: слово в нижнем регистре (ё = е) → позиция ударной гласной
def build_stress_dict():
    result = {}
    for word in FIPI_STRESS_LIST:
        key = word.lower().replace("ё", "е")
        idx = stress_index(word)
        if idx is None or result.get(key, idx) != idx:
            raise ValueError(f"ошибка в орфоэпическом списке скрипта: {word}")
        result[key] = idx
    return result



# Пронумерованные строки условия «1) …» → {номер: строка}
def numbered_lines(text):
    return dict(re.findall(r"^(\d)\) (.+)$", text, re.M))



# Пронумерованные предложения текста «(1)…(2)…» → {номер: предложение}
def numbered_sentences(text):
    parts = re.split(r"\((\d+)\)", text)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts) - 1, 2)}



# Задание 4: номера вариантов, где ударение выделено верно
def check_stress(task, stress):
    good = []
    for num, word in sorted(numbered_lines(task["text"]).items()):
        key = word.lower().replace("ё", "е")
        if key not in stress:
            return f"{FAIL_MARK}слова «{word}» нет в орфоэпическом списке ФИПИ"
        idx = stress_index(word)
        if idx is None:
            return f"{FAIL_MARK}в «{word}» должна быть ровно одна заглавная гласная"
        if idx == stress[key]:
            good.append(num)
    return "".join(good)



# Буква на месте «..» в шаблоне по полному написанию слова; None — шаблон и слово не совпадают
def missing_letter(pattern, word):
    pattern = re.sub(r"\(.*?\)", "", pattern).strip()
    head, sep, tail = pattern.partition("..")
    if not sep or ".." in tail:
        return None
    m = re.fullmatch(re.escape(head) + "(.+?)" + re.escape(tail), word)
    return m.group(1) if m else None



# Задания 9–12: номера рядов, где во всех словах пропущена одна и та же буква
def check_rows(task, rows):
    lines = numbered_lines(task["text"])
    if set(lines) != set(rows):
        return f"{FAIL_MARK}номера рядов в условии и в эталоне не совпадают"
    good = []
    for num in sorted(rows):
        patterns = [p.strip() for p in lines[num].split(",")]
        if len(patterns) != len(rows[num]):
            return f"{FAIL_MARK}ряд {num}: число слов в условии и в эталоне разное"
        letters = set()
        for pattern, word in zip(patterns, rows[num]):
            letter = missing_letter(pattern, word)
            if letter is None:
                return f"{FAIL_MARK}ряд {num}: «{pattern}» не совпадает с эталоном «{word}»"
            letters.add(letter)
        if len(letters) == 1:
            good.append(num)
    return "".join(good)



# Способ написания слова: дефис, раздельно или слитно
def spelling_mode(word):
    if "-" in word:
        return "дефис"
    if " " in word:
        return "раздельно"
    return "слитно"



# Задания 13–14: номера вариантов, где все выделенные слова пишутся требуемым способом
def check_join(task, mode, variants):
    lines = numbered_lines(task["text"])
    if set(lines) != set(variants):
        return f"{FAIL_MARK}номера вариантов в условии и в эталоне не совпадают"
    good = []
    for num in sorted(variants):
        fragments = ["".join(m).lower() for m in re.findall(r"\(([А-ЯЁ]+)\)(?:\(([А-ЯЁ]+)\))?([А-ЯЁ]+)", lines[num])]
        words = variants[num]
        if fragments != [re.sub(r"[ -]", "", w) for w in words]:
            return f"{FAIL_MARK}вариант {num}: выделенные слова {fragments} не совпадают с эталоном {words}"
        if all(spelling_mode(w) == mode for w in words):
            good.append(num)
    return "".join(good)



# Задание 15: позиции, где пишется искомая буква (Н или НН)
def check_nn(task, target, template):
    letters = re.findall(r"\{(н+)\}", template)
    counter = iter(range(1, len(letters) + 1))
    built = re.sub(r"\{н+\}", lambda m: f"({next(counter)})", template)
    if built not in task["text"]:
        return f"{FAIL_MARK}текст с пропусками не совпадает с эталоном"
    return "".join(str(i + 1) for i, letter in enumerate(letters) if letter == target)




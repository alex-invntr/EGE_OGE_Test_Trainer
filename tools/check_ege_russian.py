# Задания 17–20: номера позиций, где стоит запятая
def check_positions(task, template):
    marks = re.findall(r"\{(,?)\}", template)
    counter = iter(range(1, len(marks) + 1))
    built = re.sub(r"\{,?\}", lambda m: f" ({next(counter)})", template)
    if built not in task["text"]:
        return f"{FAIL_MARK}предложение с цифрами не совпадает с эталоном"
    return "".join(str(i + 1) for i, mark in enumerate(marks) if mark == ",")




# векторным произведением, тестовые ответы сверяются с эталоном, структура проверяется в bank_common.
# Запуск из корня проекта: python -I tools/check_oge_physics.py banks/oge_physics.js

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bank_common import load_bank, report

G = 10                     # ускорение свободного падения в задачах ОГЭ, м/с²
C_WATER = 4200             # удельная теплоёмкость воды, Дж/(кг·°С)
LAMBDA_ICE = 3.3e5         # удельная теплота плавления льда, Дж/кг
Q_WOOD = 1.0e7             # удельная теплота сгорания дров, Дж/кг
C_LIGHT = 3e8              # скорость света в вакууме, м/с



# Векторное произведение — для проверки правил буравчика и левой руки
def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])



# Направление линий поля прямого тока: B ~ I × r. Ток «от нас» = −z, точка над проводником = +y
def field_direction_above_wire():
    b = cross((0, 0, -1), (0, 1, 0))
    return "по часовой стрелке" if b[0] > 0 else "против часовой стрелки"



# Сила Ампера F ~ I·L × B: ток вниз (−y), поле «к нам» (+z)
def ampere_force_direction():
    f = cross((0, -1, 0), (0, 0, 1))
    return {(1, 0, 0): "вправо", (-1, 0, 0): "влево"}.get(f, "не в плоскости экрана")



# Во сколько раз изменилось сопротивление провода R = ρl/S при новой длине и площади сечения (в долях прежних)
def resistance_ratio(length_factor, area_factor):
    return length_factor / area_factor



